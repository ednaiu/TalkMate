def for_language(values, language):
    """Пороги для языка речи: у английской речи своя норма темпа, остальные пороги общие."""
    values = dict(values)
    if language == "en":
        values["rate_slow"] = values.get("rate_slow_en", DEFAULT_THRESHOLDS["rate_slow_en"])
        values["rate_fast"] = values.get("rate_fast_en", DEFAULT_THRESHOLDS["rate_fast_en"])
    return values
